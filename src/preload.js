const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('elearnApp', {
  back: () => ipcRenderer.send('back'),
  forward: () => ipcRenderer.send('forward'),
  exit: () => ipcRenderer.send('exit'),
  info: () => ipcRenderer.sendSync('info'),
  focusMain: () => ipcRenderer.send('focusMain'),
  onNavState: (cb) => ipcRenderer.on('nav', (e, s) => cb(s)),
  scanSources: () => ipcRenderer.invoke('scanSources'),
  pickSource: () => ipcRenderer.invoke('pickSource'),
  importData: (src, copy) => ipcRenderer.invoke('importData', src, copy),
  exportPdf: (url) => ipcRenderer.invoke('exportPdf', url),
  onProgress: (cb) => ipcRenderer.on('progress', (e, p) => cb(p)),
  // aggiornamenti
  updateInfo: () => ipcRenderer.sendSync('upd-info'),
  updateStart: () => ipcRenderer.send('upd-start'),
  updateCheck: () => ipcRenderer.invoke('upd-check'),
  onUpdate: (cb) => ipcRenderer.on('upd', (e, p) => cb(p)),
  // segnalazioni / registro
  report: () => ipcRenderer.send('report'),
  openLog: () => ipcRenderer.send('open-log'),
  statsGet: () => ipcRenderer.sendSync('stats-get'),
  statsSet: (on) => ipcRenderer.send('stats-set', on),
  lang: () => ipcRenderer.sendSync('ui-lang'),
  kvGet: (k) => ipcRenderer.sendSync('kv-get', k),
  kvSet: (k, v) => ipcRenderer.send('kv-set', k, v),
  reportPage: (info) => ipcRenderer.send('report-page', info),
  backupExport: () => ipcRenderer.invoke('backup-export'),
  backupImport: () => ipcRenderer.invoke('backup-import'),
  photoAdd: (node) => ipcRenderer.invoke('photo-add', node),
  photoDel: (node, f) => ipcRenderer.invoke('photo-del', node, f),
  openVideo: (id, title) => ipcRenderer.send('video-open', id, title),
  // schede
  tabNew: (url) => ipcRenderer.send('tab-new', url),
  tabOpen: (url) => ipcRenderer.send('tab-open', url),
  tabSelect: (i) => ipcRenderer.send('tab-select', i),
  tabClose: (i) => ipcRenderer.send('tab-close', i),
  tabCycle: (d) => ipcRenderer.send('tab-cycle', d),
  reloadAll: () => ipcRenderer.send('reload-all'),
});
